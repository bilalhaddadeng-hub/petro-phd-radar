def _shift(level: str, step: int) -> str:
    idx = _ORDER.index(level) if level in _ORDER else 1
    return _ORDER[max(0, min(len(_ORDER) - 1, idx + step))]


def tier_info(g: Dict, n_recent: Optional[int] = None) -> Dict:
    """يعيد التصنيف مع تعديل حي: الازدحام الشديد في الفحص الفعلي يخفض المستوى الأرجح ويشدد الحكم."""
    t = dict(TIERS[g["id"]])
    notes = []
    if n_recent is not None and n_recent > 200 and t["kind"] not in ("new_data",):
        t["likely"] = _shift(t["likely"], -1)
        t["risk"] = min(5, t["risk"] + 1)
        if t["verdict"] == "go":
            t["verdict"] = "cond"
        elif t["verdict"] == "cond":
            t["verdict"] = "weak"
        notes.append(f"ازدحام فعلي شديد ({n_recent} ورقة مطابقة): خُفّض التصنيف.")
    elif n_recent is not None and n_recent > 60 and t["kind"] in ("regional_case", "benchmark") and t["verdict"] == "go":
        t["verdict"] = "cond"
        notes.append(f"ازدحام متوسط-مرتفع ({n_recent} ورقة): أصبح الحكم مشروطاً.")
    t["notes"] = notes
    t["kind_label"] = KIND_LABEL[t["kind"]]
    t["verdict_label"] = VERDICT_ICON[t["verdict"]]
    return t


def tier_line(g: Dict, n_recent: Optional[int] = None) -> str:
    t = tier_info(g, n_recent)
    return f"{t['verdict_label']} | واقعي {t['likely']} (الأعلى {t['best']}) | قبول {t['risk']}/5"


VERDICT_MEANING = {
    "go": "تستحق البدء إن توفرت لك الشروط الأساسية",
    "cond": "تستحق، لكن بشروط محددة (انظر «تضعف إذا» أدناه)",
    "weak": "لا أنصح بها الآن كمشروع رئيسي",
}
RISK_MEANING = {1: "سهل القبول", 2: "قبول معقول", 3: "قبول متوسط الصعوبة", 4: "قبول صعب", 5: "شبه مستحيل دون عناصر استثنائية"}


def tier_block(g: Dict, n_recent: Optional[int] = None) -> str:
    t = tier_info(g, n_recent)
    lines = ["🏷️ *تقييم النشر:*",
             f"• الحكم: {t['verdict_label']} ({VERDICT_MEANING[t['verdict']]})",
             f"• نوع المساهمة: {t['kind_label']}",
             f"• المستوى الواقعي: {t['likely']} " + ("(وهو سقفها الواقعي أيضاً)" if t['likely'] == t['best'] else f"(الأعلى {t['best']} إن نُفِّذت بامتياز)"),
             f"• صعوبة القبول: {t['risk']}/5 ({RISK_MEANING[t['risk']]})",
             f"• تضعف الفجوة إذا: {t['weak_if']}"]
    lines += [f"• تعديل حي: {n}" for n in t["notes"]]
    return "\n".join(lines)
